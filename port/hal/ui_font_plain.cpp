/* gl[0..94] = chars 32..126 at 96 px per em; the atlas is *aw x *ah 8-bit coverage. */
void ui_font_plain_build(UiGlyphSrc *gl, std::vector<uint8_t> *atlas, int *aw, int *ah)
{
    const int S = 10, AW = 1024;
    int x = 0, y = 0, rowh = 0;
    struct Placed { int ch, x, y, w, h, adv; const char *rows; };
    std::vector<Placed> pl;
    for (const PG &g : kPlain) {
        int w = 0, nrows = 0, cur = 0;
        if (g.rows[0]) {
            for (const char *p = g.rows; ; ++p) {
                if (*p == '/' || !*p) { if (cur > w) w = cur; ++nrows; cur = 0; if (!*p) break; }
                else ++cur;
            }
        }
        const int gw = w * S, gh = nrows * S;
        if (x + gw + 2 > AW) { x = 0; y += rowh + 2; rowh = 0; }
        pl.push_back({g.ch, x, y, gw, gh, g.adv >= 0 ? g.adv * S : (w + 1) * S, g.rows});
        x += gw + 2;
        if (gh > rowh) rowh = gh;
    }
    const int AH = y + rowh + 2;
    atlas->assign((size_t)AW * AH, 0);
    memset(gl, 0, sizeof(UiGlyphSrc) * 95);
    for (int i = 0; i < 95; ++i) { gl[i].ch = 32 + i; gl[i].adv = 40.f; }
    for (const Placed &P : pl) {
        UiGlyphSrc &G = gl[P.ch - 32];
        G.ch = P.ch; G.x = P.x; G.y = P.y; G.w = P.w; G.h = P.h; G.bx = 0; G.by = -7 * S; G.adv = (float)P.adv;
        if (!P.rows[0]) continue;
        int col = 0, row = 0;
        for (const char *p = P.rows; ; ++p) {
            if (*p == '/' || !*p) { ++row; col = 0; if (!*p) break; continue; }
            if (*p == '#')
                for (int dy = 0; dy < S; ++dy)
                    for (int dx = 0; dx < S; ++dx) (*atlas)[(size_t)(P.y + row * S + dy) * AW + P.x + col * S + dx] = 255;
            ++col;
        }
    }
    *aw = AW; *ah = AH;
}
