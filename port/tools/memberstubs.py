#!/usr/bin/env python3
"""memberstubs -- loud placeholder definitions for class members the link still lacks.

    python port/tools/memberstubs.py --unresolved <list> --out port/hal/portsync3_member_stubs.cpp [--have <file>]

For every unresolved line of the form
    "public: [virtual|static] <ret> __thiscall|__cdecl <Class>::<name>(<params>)[ const]" (?decorated)
whose class has a header include/<Class>.h, emit a definition that reports once
on stderr ("UNMATCHED member entered") and returns zero. They exist so the link
completes while each missing body is still visible: a hit in a log is a finding.
Structors are skipped (they need a ruling), and so is any member whose parameter
list names a type this tool cannot spell back (a lambda-ish / pointer-to-member).

The file is rewritten from the unresolved list given, NOT accumulated: a stub
that another fix has since made unnecessary would otherwise define the member
twice. Feed it the latest link's list (parse_link output) after the other
families are settled.
"""
import argparse
import os
import re
import sys

SIG = re.compile(r'^"public: (?P<virt>virtual |static )?(?P<ret>[^()]*?) (?P<conv>__thiscall|__cdecl) '
                 r'(?P<cls>\w+)::(?P<name>\w+)\((?P<params>[^)]*)\)(?P<const> const)?" \((?P<dec>\?[^)]*)\)')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--unresolved", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    repo = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
    rows = {}
    if os.path.isfile(a.out):
        text = open(a.out, encoding="utf-8").read()
        for m in re.finditer(r"^// ROW (\S+)\n(.*?)\n(?=// ROW|\Z)", text, re.S | re.M):
            rows[m.group(1)] = m.group(2)
    skipped = []
    for line in open(a.unresolved, encoding="utf-8", errors="replace"):
        line = line.split("  <- ")[0].strip()
        m = SIG.match(line)
        if not m:
            continue
        cls, name = m.group("cls"), m.group("name")
        if name == cls or name.startswith("~"):
            skipped.append((line, "structor"))
            continue
        if "::*" in m.group("params"):
            skipped.append((line, "member-pointer parameter"))
            continue
        hdr = os.path.join(repo, "include", cls + ".h")
        if not os.path.isfile(hdr):
            skipped.append((line, "no include/%s.h" % cls))
            continue
        ret = m.group("ret").strip()
        params = m.group("params").strip()
        params = "" if params == "void" else params
        key = m.group("dec")
        plist = ""
        if params:
            parts = [p.strip() for p in re.split(r",(?![^<]*>)", params)]
            plist = ", ".join("%s a%d" % (p, i) for i, p in enumerate(parts))
        body = "{ port_unmatched_hit(\"%s::%s\"); %s}" % (
            cls, name, "" if ret == "void" else "return (%s)0; " % ret if "*" in ret or "&" in ret else "return 0; ")
        if ret.endswith("&") or "struct" in ret and "*" not in ret and ret != "void":
            skipped.append((line, "return type %r" % ret))
            continue
        rows[key] = '#include "%s.h"\n%s %s::%s(%s)%s %s' % (
            cls, ret, cls, name, plist, m.group("const") or "", body)
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// GENERATED by port/tools/memberstubs.py -- loud placeholders, see that file.\n")
        fh.write("// Each body reports once on stderr and returns zero. A hit in a log is a finding.\n")
        fh.write('#include <cstdio>\n#include "types.h"\n')
        fh.write("static void port_unmatched_hit(const char *what)\n{\n")
        fh.write("    static const char *seen[256];\n    for (int i = 0; i < 256; ++i) {\n")
        fh.write("        if (seen[i] == what) return;\n")
        fh.write("        if (!seen[i]) { seen[i] = what; break; }\n    }\n")
        fh.write('    std::fprintf(stderr, "  [portsync3] UNMATCHED member entered: %s\\n", what);\n')
        fh.write("    std::fflush(stderr);\n}\n\n")
        for key in sorted(rows):
            fh.write("// ROW %s\n%s\n\n" % (key, rows[key]))
    print("memberstubs: %d rows -> %s" % (len(rows), a.out))
    for line, why in skipped:
        print("  skipped: %s (%s)" % (line[:90], why))


if __name__ == "__main__":
    main()
